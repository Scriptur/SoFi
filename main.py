import os

# Запитуємо у користувача шлях до робочої теки
start_dir = input("Введіть шлях до робочої теки: ")

# Перевіряємо, чи існує вказана тека
if not os.path.exists(start_dir):
    print("\033[91mВказана тека не існує.\033[0m") # червоним кольором
    exit(0)
else:
    os.chdir(start_dir)  # Змінюємо поточну робочу теку на вказану

# Далі мій код
print(f"\033[38;5;118mРобоча тека знаходиться за адресою {start_dir}\033[0m") # темно-салатовим кольором